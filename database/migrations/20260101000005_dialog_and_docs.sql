-- ---------------------------------------------------------------------------
-- Conversations. Each patient<->doctor thread exists twice: the patient's copy
-- (assistant = mediaid) and the doctor's mirror (assistant = medidoc), linked
-- through mirror_conversation_id. user_id is always the owner of that copy.
-- ---------------------------------------------------------------------------
CREATE TYPE dialog.assistant_type AS ENUM ('mediaid', 'medidoc');
CREATE TYPE dialog.message_role AS ENUM ('system', 'assistant', 'user');

CREATE TABLE dialog.conversations (
    id                      uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id                 integer NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    patient_id              integer REFERENCES public.patients(id) ON DELETE CASCADE,
    doctor_id               integer REFERENCES public.doctors(id) ON DELETE CASCADE,
    assistant               dialog.assistant_type NOT NULL DEFAULT 'mediaid',
    state                   text NOT NULL DEFAULT 'active' CHECK (state IN ('active','inactive','closed','test')),
    region_id               integer REFERENCES public.regions(id),
    mirror_conversation_id  uuid REFERENCES dialog.conversations(id) ON DELETE SET NULL,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX conversations_owner ON dialog.conversations (user_id, assistant, updated_at DESC);
CREATE INDEX conversations_patient ON dialog.conversations (patient_id);
CREATE INDEX conversations_doctor ON dialog.conversations (doctor_id);
-- One thread per patient<->doctor pair per side.
CREATE UNIQUE INDEX conversations_pair_key ON dialog.conversations (patient_id, doctor_id, assistant)
    WHERE patient_id IS NOT NULL AND doctor_id IS NOT NULL;
-- One solo AI thread per patient profile / per doctor.
CREATE UNIQUE INDEX conversations_patient_solo_key ON dialog.conversations (patient_id)
    WHERE assistant = 'mediaid' AND doctor_id IS NULL;
CREATE UNIQUE INDEX conversations_doctor_solo_key ON dialog.conversations (doctor_id)
    WHERE assistant = 'medidoc' AND patient_id IS NULL;

CREATE TABLE dialog.messages (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  uuid NOT NULL REFERENCES dialog.conversations(id) ON DELETE CASCADE,
    role             dialog.message_role NOT NULL,
    content          jsonb NOT NULL,
    processed_by_ai  boolean NOT NULL DEFAULT false,
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX messages_conversation ON dialog.messages (conversation_id, id);

-- Bump the parent conversation whenever a message is written.
CREATE OR REPLACE FUNCTION dialog.touch_conversation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE dialog.conversations SET updated_at = now() WHERE id = NEW.conversation_id;
    RETURN NEW;
END;
$$;
CREATE TRIGGER messages_touch_conversation AFTER INSERT ON dialog.messages
    FOR EACH ROW EXECUTE FUNCTION dialog.touch_conversation();

-- Every patient profile and every doctor gets a solo thread with the assistant.
CREATE OR REPLACE FUNCTION dialog.create_patient_solo_conversation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.user_id IS NOT NULL THEN
        INSERT INTO dialog.conversations (user_id, patient_id, assistant)
        VALUES (NEW.user_id, NEW.id, 'mediaid')
        ON CONFLICT DO NOTHING;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER patients_solo_conversation AFTER INSERT ON public.patients
    FOR EACH ROW EXECUTE FUNCTION dialog.create_patient_solo_conversation();

CREATE OR REPLACE FUNCTION dialog.create_doctor_solo_conversation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.user_id IS NOT NULL THEN
        INSERT INTO dialog.conversations (user_id, doctor_id, assistant)
        VALUES (NEW.user_id, NEW.id, 'medidoc')
        ON CONFLICT DO NOTHING;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER doctors_solo_conversation AFTER INSERT ON public.doctors
    FOR EACH ROW EXECUTE FUNCTION dialog.create_doctor_solo_conversation();

-- AI long-term memory: rolling compaction of older messages.
CREATE TABLE dialog.conversation_compactions (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  uuid NOT NULL REFERENCES dialog.conversations(id) ON DELETE CASCADE,
    summary_text     text NOT NULL,
    from_message_id  bigint,
    to_message_id    bigint NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX conversation_compactions_latest ON dialog.conversation_compactions (conversation_id, to_message_id DESC);

-- Doctor-facing clinical brief of the patient's thread.
CREATE TABLE dialog.medibrief_summaries (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id         uuid NOT NULL REFERENCES dialog.conversations(id) ON DELETE CASCADE,
    mirror_conversation_id  uuid REFERENCES dialog.conversations(id) ON DELETE SET NULL,
    summary_text            text NOT NULL,
    from_message_id         bigint,
    to_message_id           bigint NOT NULL,
    created_at              timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX medibrief_summaries_latest ON dialog.medibrief_summaries (conversation_id, to_message_id DESC);

-- Patient-facing plain-language explanation of the doctor's thread.
CREATE TABLE dialog.mediexplain_summaries (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  uuid NOT NULL REFERENCES dialog.conversations(id) ON DELETE CASCADE,
    summary_text     text NOT NULL,
    from_message_id  bigint,
    to_message_id    bigint NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX mediexplain_summaries_latest ON dialog.mediexplain_summaries (conversation_id, to_message_id DESC);

CREATE VIEW dialog.messages_view AS
SELECT id, conversation_id, role::text AS role, content, processed_by_ai, created_at
FROM dialog.messages;

CREATE VIEW dialog.conversation_details_view AS
SELECT
    c.id, c.mirror_conversation_id,
    cc.summary_text AS compact_summary, cc.to_message_id AS compact_to_message,
    mb.summary_text AS medibrief_summary, mb.to_message_id AS medibrief_to_message,
    me.summary_text AS mediexplain_summary, me.to_message_id AS mediexplain_to_message
FROM dialog.conversations c
LEFT JOIN LATERAL (
    SELECT summary_text, to_message_id FROM dialog.conversation_compactions
    WHERE conversation_id = c.id ORDER BY to_message_id DESC LIMIT 1
) cc ON true
LEFT JOIN LATERAL (
    SELECT summary_text, to_message_id FROM dialog.medibrief_summaries
    WHERE conversation_id = c.id ORDER BY to_message_id DESC LIMIT 1
) mb ON true
LEFT JOIN LATERAL (
    SELECT summary_text, to_message_id FROM dialog.mediexplain_summaries
    WHERE conversation_id = c.id ORDER BY to_message_id DESC LIMIT 1
) me ON true;

CREATE VIEW dialog.conversations_view AS
SELECT
    c.id, c.user_id, c.patient_id, c.doctor_id, c.assistant, c.state, c.region_id,
    c.mirror_conversation_id, c.created_at, c.updated_at,
    trim(coalesce(p.first_name, '') || ' ' || coalesce(p.last_name, '')) AS patient_name,
    pp.avatar_url AS patient_image,
    CASE WHEN p.dob IS NOT NULL THEN date_part('year', age(p.dob))::int END AS patient_current_age,
    p.gender AS patient_gender,
    trim(coalesce(d.first_name, '') || ' ' || coalesce(d.last_name, '')) AS doctor_name,
    d.avatar_url AS doctor_image,
    s.name AS doctor_specialty_name,
    lm.content->>'text_io' AS last_message_text,
    lm.created_at AS last_message_timestamp
FROM dialog.conversations c
LEFT JOIN public.patients p ON p.id = c.patient_id
LEFT JOIN auth.user_profiles pp ON pp.user_id = p.user_id
LEFT JOIN public.doctors d ON d.id = c.doctor_id
LEFT JOIN public.specialties s ON s.id = d.specialty_id
LEFT JOIN LATERAL (
    SELECT content, created_at FROM dialog.messages
    WHERE conversation_id = c.id ORDER BY id DESC LIMIT 1
) lm ON true;

-- ---------------------------------------------------------------------------
-- Document vault. Files live in object storage; these tables hold metadata
-- and who a document has been shared with.
-- ---------------------------------------------------------------------------
CREATE TABLE docs.patient_docs (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id     integer NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
    external_id    uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    blob_name      text NOT NULL,
    original_name  text NOT NULL,
    mime_type      text NOT NULL,
    size_bytes     bigint,
    status         text NOT NULL DEFAULT 'available',
    created_at     timestamptz NOT NULL DEFAULT now(),
    deleted_at     timestamptz
);
CREATE INDEX patient_docs_owner ON docs.patient_docs (patient_id) WHERE deleted_at IS NULL;

CREATE TABLE docs.doctor_docs (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id      integer NOT NULL REFERENCES public.doctors(id) ON DELETE CASCADE,
    external_id    uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    blob_name      text NOT NULL,
    original_name  text NOT NULL,
    mime_type      text NOT NULL,
    size_bytes     bigint,
    status         text NOT NULL DEFAULT 'available',
    created_at     timestamptz NOT NULL DEFAULT now(),
    deleted_at     timestamptz
);
CREATE INDEX doctor_docs_owner ON docs.doctor_docs (doctor_id) WHERE deleted_at IS NULL;

-- A patient's document shared with a doctor.
CREATE TABLE docs.patient_shares (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_id           integer NOT NULL REFERENCES docs.patient_docs(id) ON DELETE CASCADE,
    doctor_id        integer NOT NULL REFERENCES public.doctors(id) ON DELETE CASCADE,
    conversation_id  uuid REFERENCES dialog.conversations(id) ON DELETE SET NULL,
    shared_at        timestamptz NOT NULL DEFAULT now(),
    revoked_at       timestamptz,
    UNIQUE (doc_id, doctor_id)
);

-- A doctor's document shared with a patient.
CREATE TABLE docs.doctor_shares (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_id           integer NOT NULL REFERENCES docs.doctor_docs(id) ON DELETE CASCADE,
    patient_id       integer NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
    conversation_id  uuid REFERENCES dialog.conversations(id) ON DELETE SET NULL,
    shared_at        timestamptz NOT NULL DEFAULT now(),
    revoked_at       timestamptz,
    UNIQUE (doc_id, patient_id)
);

CREATE VIEW docs.patient_vault_view AS
SELECT
    pd.patient_id, pd.external_id, pd.original_name, pd.mime_type, pd.size_bytes, pd.created_at,
    coalesce(array_agg(trim(coalesce(d.first_name, '') || ' ' || coalesce(d.last_name, '')))
             FILTER (WHERE s.id IS NOT NULL), '{}') AS shared_with,
    count(s.id)::int AS active_shares
FROM docs.patient_docs pd
LEFT JOIN docs.patient_shares s ON s.doc_id = pd.id AND s.revoked_at IS NULL
LEFT JOIN public.doctors d ON d.id = s.doctor_id
WHERE pd.deleted_at IS NULL
GROUP BY pd.id;

CREATE VIEW docs.doctor_vault_view AS
SELECT
    dd.doctor_id, dd.external_id, dd.original_name, dd.mime_type, dd.size_bytes, dd.created_at,
    coalesce(array_agg(trim(coalesce(p.first_name, '') || ' ' || coalesce(p.last_name, '')))
             FILTER (WHERE s.id IS NOT NULL), '{}') AS shared_with,
    count(s.id)::int AS active_shares
FROM docs.doctor_docs dd
LEFT JOIN docs.doctor_shares s ON s.doc_id = dd.id AND s.revoked_at IS NULL
LEFT JOIN public.patients p ON p.id = s.patient_id
WHERE dd.deleted_at IS NULL
GROUP BY dd.id;

-- Documents doctors have shared with a patient.
CREATE VIEW docs.patient_inbox_view AS
SELECT
    s.patient_id, dd.external_id, dd.original_name, dd.mime_type, s.shared_at, s.conversation_id,
    trim(coalesce(d.prefix || ' ', '') || coalesce(d.first_name, '') || ' ' || coalesce(d.last_name, '')) AS from_doctor
FROM docs.doctor_shares s
JOIN docs.doctor_docs dd ON dd.id = s.doc_id AND dd.deleted_at IS NULL
JOIN public.doctors d ON d.id = dd.doctor_id
WHERE s.revoked_at IS NULL;

-- Documents patients have shared with a doctor.
CREATE VIEW docs.doctor_inbox_view AS
SELECT
    s.doctor_id, pd.external_id, pd.original_name, pd.mime_type, s.shared_at, s.conversation_id,
    trim(coalesce(p.first_name, '') || ' ' || coalesce(p.last_name, '')) AS from_patient
FROM docs.patient_shares s
JOIN docs.patient_docs pd ON pd.id = s.doc_id AND pd.deleted_at IS NULL
JOIN public.patients p ON p.id = pd.patient_id
WHERE s.revoked_at IS NULL;

