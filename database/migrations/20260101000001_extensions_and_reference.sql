-- Shared trigger function: keeps updated_at current on UPDATE.
CREATE OR REPLACE FUNCTION public.set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------------
-- Geography & languages
-- ---------------------------------------------------------------------------
CREATE TABLE public.countries (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL UNIQUE,
    iso_code    char(2) UNIQUE,
    phone_code  text
);

CREATE TABLE public.regions (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id  integer NOT NULL REFERENCES public.countries(id) ON DELETE CASCADE,
    name        text NOT NULL,
    UNIQUE (country_id, name)
);

CREATE TABLE public.languages (
    id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  text NOT NULL UNIQUE,
    code  text NOT NULL UNIQUE
);

-- ---------------------------------------------------------------------------
-- Medical specialties
-- ---------------------------------------------------------------------------
CREATE TABLE public.specialty_super_categories (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text NOT NULL UNIQUE,
    description  text,
    icon         text
);

CREATE TABLE public.specialties (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               text NOT NULL UNIQUE,
    super_category_id  integer REFERENCES public.specialty_super_categories(id) ON DELETE SET NULL
);

CREATE TABLE public.healthcare_providers (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    address     jsonb,
    country_id  integer REFERENCES public.countries(id),
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Clinical knowledge base (used by the offline clinical-coding job)
-- ---------------------------------------------------------------------------
CREATE TABLE public.conditions (
    condition_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name  text NOT NULL,
    icd10         varchar(20),
    category      text,
    is_chronic    boolean NOT NULL DEFAULT false,
    synonyms      text[] NOT NULL DEFAULT '{}'
);
CREATE INDEX conditions_name_trgm ON public.conditions USING gin (display_name gin_trgm_ops);

CREATE TABLE public.procedures (
    procedure_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text NOT NULL,
    description     text,
    procedure_code  text,
    cpt_code        text,
    icd10_pcs_code  text,
    synonyms        text[] NOT NULL DEFAULT '{}'
);
CREATE INDEX procedures_name_trgm ON public.procedures USING gin (name gin_trgm_ops);

CREATE TABLE public.vitals (
    vital_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vital_key     text NOT NULL UNIQUE,
    display_name  text NOT NULL,
    category      text NOT NULL DEFAULT 'other'
                  CHECK (category IN ('vitals','lifestyle','body_metrics','vaccines','immunization',
                                      'biological','reproductive','other')),
    unit          text,
    synonyms      text[] NOT NULL DEFAULT '{}'
);
CREATE INDEX vitals_name_trgm ON public.vitals USING gin (display_name gin_trgm_ops);

CREATE TABLE public.vital_reference_ranges (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vital_id    integer REFERENCES public.vitals(vital_id) ON DELETE CASCADE,
    vital_key   text NOT NULL,
    gender      text NOT NULL DEFAULT 'ALL' CHECK (gender IN ('M','F','ALL')),
    age_min     integer NOT NULL DEFAULT 0,
    age_max     integer NOT NULL DEFAULT 150,
    thresholds  jsonb NOT NULL DEFAULT '[]',
    is_active   boolean NOT NULL DEFAULT true
);
CREATE INDEX vital_reference_ranges_key ON public.vital_reference_ranges (vital_key) WHERE is_active;

-- Fuzzy lookup helpers: map free-text clinician input to knowledge-base rows.
CREATE OR REPLACE FUNCTION public.search_conditions_fuzzy(q text, min_score real DEFAULT 0.3)
RETURNS TABLE (condition_id integer, display_name text, score real)
LANGUAGE sql STABLE AS $$
    SELECT c.condition_id, c.display_name,
           greatest(similarity(lower(c.display_name), lower(q)),
                    coalesce((SELECT max(similarity(lower(s), lower(q))) FROM unnest(c.synonyms) s), 0)) AS score
    FROM public.conditions c
    WHERE lower(c.display_name) % lower(q)
       OR EXISTS (SELECT 1 FROM unnest(c.synonyms) s WHERE lower(s) % lower(q))
    ORDER BY score DESC
$$;

CREATE OR REPLACE FUNCTION public.search_procedures_fuzzy(q text)
RETURNS TABLE (procedure_id integer, name text, score real)
LANGUAGE sql STABLE AS $$
    SELECT p.procedure_id, p.name,
           greatest(similarity(lower(p.name), lower(q)),
                    coalesce((SELECT max(similarity(lower(s), lower(q))) FROM unnest(p.synonyms) s), 0)) AS score
    FROM public.procedures p
    WHERE lower(p.name) % lower(q)
       OR EXISTS (SELECT 1 FROM unnest(p.synonyms) s WHERE lower(s) % lower(q))
    ORDER BY score DESC
$$;

CREATE OR REPLACE FUNCTION public.search_vitals_fuzzy(q text)
RETURNS TABLE (vital_id integer, vital_key text, score real)
LANGUAGE sql STABLE AS $$
    SELECT v.vital_id, v.vital_key,
           greatest(similarity(lower(v.display_name), lower(q)),
                    similarity(lower(v.vital_key), lower(q)),
                    coalesce((SELECT max(similarity(lower(s), lower(q))) FROM unnest(v.synonyms) s), 0)) AS score
    FROM public.vitals v
    WHERE lower(v.display_name) % lower(q)
       OR lower(v.vital_key) % lower(q)
       OR EXISTS (SELECT 1 FROM unnest(v.synonyms) s WHERE lower(s) % lower(q))
    ORDER BY score DESC
$$;

