CREATE VIEW public.medical_visits_view AS
SELECT
    v.id, v.patient_id, v.doctor_id,
    trim(coalesce(d.first_name, '') || ' ' || coalesce(d.last_name, '')) AS doctor_name,
    v.hc_provider_id, hp.name AS healthcare_provider_name,
    v.start_time, v.end_time, v.visit_type::text AS visit_type, v.visit_details,
    v.created_at, v.updated_at, v.created_by
FROM public.medical_visits v
JOIN public.doctors d ON d.id = v.doctor_id
LEFT JOIN public.healthcare_providers hp ON hp.id = v.hc_provider_id;

CREATE VIEW public.medical_conditions_view AS
SELECT
    mc.id, mc.patient_id, mc.doctor_id,
    trim(coalesce(d.first_name, '') || ' ' || coalesce(d.last_name, '')) AS doctor_name,
    mc.diagnosis_date, mc.condition_id, mc.condition_text,
    coalesce(k.display_name, mc.condition_text) AS display_name,
    k.icd10, k.category, mc.severity, coalesce(k.is_chronic, false) AS is_chronic,
    mc.resolved_date, mc.is_active, mc.notes AS clinical_notes, mc.created_at,
    CASE
        WHEN mc.resolved_date IS NOT NULL OR NOT mc.is_active THEN 'resolved'
        WHEN coalesce(k.is_chronic, false) THEN 'chronic'
        ELSE 'active'
    END AS clinical_status
FROM public.medical_conditions mc
LEFT JOIN public.conditions k ON k.condition_id = mc.condition_id
LEFT JOIN public.doctors d ON d.id = mc.doctor_id;

-- Latest diagnosis per (patient, condition).
CREATE VIEW public.medical_conditions_latest_view AS
SELECT DISTINCT ON (patient_id, coalesce(condition_id::text, lower(condition_text))) *
FROM public.medical_conditions_view
ORDER BY patient_id, coalesce(condition_id::text, lower(condition_text)), diagnosis_date DESC NULLS LAST, id DESC;

CREATE VIEW public.medical_notes_view AS
SELECT
    n.id, n.patient_id, n.doctor_id,
    trim(coalesce(d.first_name, '') || ' ' || coalesce(d.last_name, '')) AS doctor_name,
    n.note_date, n.note_details, n.status, n.created_at, n.updated_at
FROM public.medical_notes n
LEFT JOIN public.doctors d ON d.id = n.doctor_id
WHERE n.status = 'active';

-- One row per medication inside each prescription.
CREATE VIEW public.medications_view AS
WITH items AS (
    SELECT
        p.id AS prescription_id, p.patient_id, p.doctor_id, p.date_prescribed, p.notes AS prescription_notes,
        m.item, m.ord,
        NULLIF(substring(coalesce(m.item->>'duration_days', m.item->>'duration') FROM '\d+'), '')::int AS duration_days
    FROM public.medical_prescriptions p
    CROSS JOIN LATERAL jsonb_array_elements(p.medications) WITH ORDINALITY AS m(item, ord)
)
SELECT
    (i.prescription_id::bigint * 1000 + i.ord) AS id,
    i.prescription_id, i.patient_id, i.doctor_id,
    trim(coalesce(d.first_name, '') || ' ' || coalesce(d.last_name, '')) AS doctor_name,
    i.date_prescribed,
    coalesce(i.item->>'medication_name', i.item->>'name') AS medication_name,
    coalesce(i.item->>'dosage', i.item->>'dose') AS dose,
    i.item->>'frequency' AS frequency,
    i.duration_days,
    i.item->>'form' AS form,
    i.item->>'purpose' AS purpose,
    i.prescription_notes AS notes,
    i.date_prescribed AS start_date,
    CASE WHEN i.duration_days IS NOT NULL THEN i.date_prescribed + i.duration_days END AS end_date,
    CASE WHEN i.duration_days IS NOT NULL AND i.date_prescribed + i.duration_days < current_date
         THEN 'completed' ELSE 'active' END AS status
FROM items i
LEFT JOIN public.doctors d ON d.id = i.doctor_id;

