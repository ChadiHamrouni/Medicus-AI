CREATE TABLE public.medical_procedures (
    id                         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id                 integer NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
    doctor_id                  integer REFERENCES public.doctors(id) ON DELETE SET NULL,
    procedure_id               integer REFERENCES public.procedures(procedure_id),
    procedure_text             text NOT NULL,
    healthcare_provider_text   text,
    hc_provider_id             integer REFERENCES public.healthcare_providers(id),
    scheduled_date             date NOT NULL,
    scheduled_time             time,
    location                   jsonb,
    summary                    text,
    completed_at               timestamptz,
    cancelled_at               timestamptz,
    created_at                 timestamptz NOT NULL DEFAULT now(),
    updated_at                 timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX medical_procedures_patient ON public.medical_procedures (patient_id, scheduled_date);
CREATE INDEX medical_procedures_doctor ON public.medical_procedures (doctor_id, scheduled_date);

CREATE TABLE public.medical_procedure_details (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedure_id    integer NOT NULL REFERENCES public.medical_procedures(id) ON DELETE CASCADE,
    actor_id        integer,
    entry_type      text NOT NULL,
    content         jsonb NOT NULL DEFAULT '[]',     -- [{"text":..,"value":..,"unit":..}]
