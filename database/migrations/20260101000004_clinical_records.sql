CREATE VIEW public.medical_procedures_view AS
SELECT
    mp.id, mp.patient_id, mp.doctor_id,
    trim(coalesce(d.first_name, '') || ' ' || coalesce(d.last_name, '')) AS doctor_name,
    mp.procedure_id, mp.procedure_text,
    coalesce(k.name, mp.procedure_text) AS display_name,
    k.procedure_code, k.cpt_code, k.icd10_pcs_code,
    mp.hc_provider_id, coalesce(hp.name, mp.healthcare_provider_text) AS healthcare_provider_name,
    mp.scheduled_date, mp.scheduled_time, mp.location, mp.summary,
    CASE
        WHEN mp.cancelled_at IS NOT NULL THEN 'cancelled'
        WHEN mp.completed_at IS NOT NULL THEN 'completed'
        ELSE 'scheduled'
    END AS status,
    mp.completed_at, mp.cancelled_at, mp.created_at, mp.updated_at
FROM public.medical_procedures mp
LEFT JOIN public.procedures k ON k.procedure_id = mp.procedure_id
LEFT JOIN public.doctors d ON d.id = mp.doctor_id
LEFT JOIN public.healthcare_providers hp ON hp.id = mp.hc_provider_id;

-- One row per logged observation inside a procedure-detail entry.
CREATE VIEW public.medical_procedure_details_view AS
SELECT
    pd.id, pd.procedure_id, pd.actor_id,
    CASE WHEN dr.id IS NOT NULL THEN 'doctor' ELSE 'clinician' END AS actor_role,
    pd.entry_type, pd.severity_level, pd.logged_at,
    e.elem->>'text' AS event_text,
    e.elem->>'value' AS event_value,
    e.elem->>'unit' AS event_unit,
    mp.procedure_text,
    coalesce(k.name, mp.procedure_text) AS procedure_name,
    k.description AS procedure_description
FROM public.medical_procedure_details pd
JOIN public.medical_procedures mp ON mp.id = pd.procedure_id
LEFT JOIN public.procedures k ON k.procedure_id = mp.procedure_id
LEFT JOIN public.doctors dr ON dr.id = pd.actor_id
CROSS JOIN LATERAL jsonb_array_elements(
    CASE WHEN jsonb_typeof(pd.content) = 'array' THEN pd.content ELSE jsonb_build_array(pd.content) END
) AS e(elem);

-- One row per measured value, resolved against the vitals knowledge base.
CREATE VIEW public.medical_vitals_view AS
SELECT
    mv.id, mv.patient_id, mv.doctor_id,
    trim(coalesce(d.first_name, '') || ' ' || coalesce(d.last_name, '')) AS doctor_name,
    hp.name AS healthcare_provider_name,
    mv.recorded_at,
    v.vital_id,
    coalesce(v.vital_key, lower(x.elem->>'vital_text')) AS vital_name,
    v.category AS vital_category,
    coalesce(v.display_name, x.elem->>'vital_text') AS display_name,
    x.elem->>'vital_value' AS vital_value,
    x.elem->>'vital_text' AS vital_text,
    v.unit,
    (mv.meta_data->>'convo_id')::bigint AS convo_id,
    (mv.meta_data->>'message_id')::bigint AS message_id,
    mv.meta_data->>'tool' AS tool,
    mv.meta_data->>'actor_role' AS actor_role,
    (mv.meta_data->>'actor_user_id')::int AS actor_user_id
FROM public.medical_vitals mv
CROSS JOIN LATERAL jsonb_array_elements(
    CASE WHEN jsonb_typeof(mv.vital_values) = 'array' THEN mv.vital_values ELSE '[]'::jsonb END
) AS x(elem)
-- Resolve the catalog entry by id, else by name/synonym (assistants and imports
-- often store only free text such as "blood pressure" or "pulse").
LEFT JOIN LATERAL (
    SELECT c.* FROM public.vitals c
    WHERE c.vital_id = (x.elem->>'vital_id')::int
       OR lower(trim(x.elem->>'vital_text')) IN (lower(c.vital_key), lower(c.display_name))
       OR lower(trim(x.elem->>'vital_text')) = ANY (SELECT lower(s) FROM unnest(c.synonyms) s)
    ORDER BY (c.vital_id = (x.elem->>'vital_id')::int) DESC NULLS LAST, c.vital_id
    LIMIT 1
) v ON true
LEFT JOIN public.doctors d ON d.id = mv.doctor_id
LEFT JOIN public.healthcare_providers hp ON hp.id = mv.healthcare_provider_id
WHERE mv.status = 'active';

CREATE VIEW public.medical_vitals_latest_view AS
SELECT DISTINCT ON (patient_id, vital_name) *
FROM public.medical_vitals_view
ORDER BY patient_id, vital_name, recorded_at DESC, id DESC;

-- Unified patient health calendar.
CREATE VIEW public.medical_events_view AS
SELECT v.id, v.id AS event_id, v.patient_id, v.doctor_id, v.doctor_name,
       (v.start_time AT TIME ZONE 'UTC')::date AS event_date,
       (v.start_time AT TIME ZONE 'UTC')::time AS event_time,
       v.healthcare_provider_name AS event_location,
       'visit'::text AS event_type, v.visit_type AS event_name,
       jsonb_build_object('visit_details', v.visit_details, 'end_time', v.end_time) AS event_details,
       NULL::text AS event_summary, v.healthcare_provider_name,
       CASE WHEN v.end_time >= now() THEN 'active' ELSE 'past' END AS status
FROM public.medical_visits_view v
UNION ALL
SELECT e.id, e.id, e.patient_id, e.doctor_id, e.doctor_name,
       e.exam_date, NULL::time, e.healthcare_provider_name,
       'exam', e.exam_type, e.exam_results, e.exam_summary, e.healthcare_provider_name,
       'past'
FROM public.medical_examinations_view e
UNION ALL
SELECT o.id, o.id, o.patient_id, o.doctor_id, o.doctor_name,
       coalesce(o.scheduled_date, o.ordered_date), o.scheduled_time, o.healthcare_provider_name,
       'exam_order', o.ordered_exam, jsonb_build_object('exam_type', o.exam_type, 'notes', o.notes),
       NULL, o.healthcare_provider_name,
       CASE WHEN coalesce(o.scheduled_date, o.ordered_date) >= current_date THEN 'active' ELSE 'past' END
FROM public.medical_exam_orders_view o
UNION ALL
SELECT p.id, p.id, p.patient_id, p.doctor_id, p.doctor_name,
       p.scheduled_date, p.scheduled_time, p.location->>'clinic_address',
       'procedure', p.display_name, p.location, p.summary, p.healthcare_provider_name,
       CASE WHEN p.status = 'scheduled' AND p.scheduled_date >= current_date THEN 'active' ELSE 'past' END
FROM public.medical_procedures_view p
WHERE p.status <> 'cancelled';

-- Doctor-side agenda: same events, keyed by doctor with the patient's name.
CREATE VIEW public.doctors_events_view AS
SELECT ev.id, ev.doctor_id, ev.patient_id,
       trim(coalesce(pt.first_name, '') || ' ' || coalesce(pt.last_name, '')) AS patient_name,
       ev.event_date, ev.event_time, ev.event_location, ev.event_type, ev.event_name,
       ev.event_details, ev.event_summary, ev.healthcare_provider_name, ev.status
FROM public.medical_events_view ev
JOIN public.patients pt ON pt.id = ev.patient_id
WHERE ev.event_type IN ('visit', 'procedure') AND ev.doctor_id IS NOT NULL;

