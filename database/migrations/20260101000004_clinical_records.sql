CREATE TYPE public.visit_type_enum AS ENUM
    ('consultation','procedure','exam','prescription','follow-up','check-up','emergency','other');

-- ---------------------------------------------------------------------------
-- Appointments
-- ---------------------------------------------------------------------------
CREATE TABLE public.medical_visits (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id      integer NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
    doctor_id       integer NOT NULL REFERENCES public.doctors(id) ON DELETE CASCADE,
    hc_provider_id  integer REFERENCES public.healthcare_providers(id),
    start_time      timestamptz NOT NULL,
    end_time        timestamptz NOT NULL,
    visit_type      public.visit_type_enum NOT NULL DEFAULT 'consultation',
    visit_details   text,
    created_by      text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CHECK (end_time > start_time),
    UNIQUE (doctor_id, patient_id, start_time),
    -- A doctor can never hold two overlapping appointments.
    EXCLUDE USING gist (doctor_id WITH =, tstzrange(start_time, end_time) WITH &&)
);
CREATE INDEX medical_visits_patient ON public.medical_visits (patient_id, start_time DESC);
CREATE TRIGGER medical_visits_updated_at BEFORE UPDATE ON public.medical_visits
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ---------------------------------------------------------------------------
-- Diagnoses (immutable; condition_id is filled in later by clinical coding)
-- ---------------------------------------------------------------------------
CREATE TABLE public.medical_conditions (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id      integer NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
    doctor_id       integer REFERENCES public.doctors(id) ON DELETE SET NULL,
    condition_id    integer REFERENCES public.conditions(condition_id),
    condition_text  text NOT NULL,
    diagnosis_date  date,
    severity        text,
    notes           text,
    resolved_date   date,
    is_active       boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX medical_conditions_patient ON public.medical_conditions (patient_id);
CREATE INDEX medical_conditions_uncoded ON public.medical_conditions (id) WHERE condition_id IS NULL;

-- ---------------------------------------------------------------------------
-- SOAP clinical notes (append-only; corrections supersede)
-- ---------------------------------------------------------------------------
CREATE TABLE public.medical_notes (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id    integer NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
    doctor_id     integer REFERENCES public.doctors(id) ON DELETE SET NULL,
    note_date     date NOT NULL DEFAULT current_date,
    note_details  jsonb NOT NULL,
    status        text NOT NULL DEFAULT 'active' CHECK (status IN ('active','superseded','entered-in-error')),
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX medical_notes_patient ON public.medical_notes (patient_id, note_date DESC) WHERE status = 'active';

-- ---------------------------------------------------------------------------
-- Prescriptions: one row per prescription, medications as a JSON array
-- ---------------------------------------------------------------------------
CREATE TABLE public.medical_prescriptions (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id       integer NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
    doctor_id        integer REFERENCES public.doctors(id) ON DELETE SET NULL,
    date_prescribed  date NOT NULL DEFAULT current_date,
    medications      jsonb NOT NULL DEFAULT '[]',
    notes            text,
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX medical_prescriptions_patient ON public.medical_prescriptions (patient_id, date_prescribed DESC);

-- ---------------------------------------------------------------------------
-- Exams: orders (intent) and examinations (results)
-- ---------------------------------------------------------------------------
CREATE TABLE public.medical_exam_orders (
    id                        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id                integer NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
    doctor_id                 integer REFERENCES public.doctors(id) ON DELETE SET NULL,
    ordered_exam              text NOT NULL,
    exam_type                 text,
    hc_provider_id            integer REFERENCES public.healthcare_providers(id),
    healthcare_provider_name  text,
    ordered_date              date NOT NULL DEFAULT current_date,
    scheduled_date            date,
    scheduled_time            time,
    notes                     text,
    is_cancelled              boolean NOT NULL DEFAULT false,
    created_at                timestamptz NOT NULL DEFAULT now(),
    updated_at                timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX medical_exam_orders_patient ON public.medical_exam_orders (patient_id);

CREATE TABLE public.medical_examinations (
    id                        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id                integer NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
    doctor_id                 integer REFERENCES public.doctors(id) ON DELETE SET NULL,
    exam_date                 date NOT NULL,
    exam_type                 text NOT NULL,
    exam_results              jsonb,
    exam_summary              text,
    hc_provider_id            integer REFERENCES public.healthcare_providers(id),
    healthcare_provider_name  text,
    created_at                timestamptz NOT NULL DEFAULT now(),
    updated_at                timestamptz NOT NULL DEFAULT now(),
    UNIQUE NULLS NOT DISTINCT (patient_id, doctor_id, exam_date, exam_type)
