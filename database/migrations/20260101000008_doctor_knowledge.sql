-- ---------------------------------------------------------------------------
-- MediKnowledge: material a doctor publishes for their patients (how a procedure
-- is done, preparation instructions, prices, clinic policies...). The doctor's
-- assistant answers patient questions from it. Documents are split into chunks;
-- search combines full-text, fuzzy matching and (optionally) embeddings.
-- ---------------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS knowledge;

CREATE TABLE knowledge.documents (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id     integer     NOT NULL REFERENCES public.doctors(id) ON DELETE CASCADE,
    title         text        NOT NULL,
    source_name   text,                         -- original file name, if uploaded
    mime_type     text,
    chunk_count   integer     NOT NULL DEFAULT 0,
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX knowledge_documents_doctor_idx ON knowledge.documents (doctor_id);

CREATE TABLE knowledge.chunks (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id   bigint  NOT NULL REFERENCES knowledge.documents(id) ON DELETE CASCADE,
    doctor_id     integer NOT NULL REFERENCES public.doctors(id) ON DELETE CASCADE,
    chunk_index   integer NOT NULL,
    content       text    NOT NULL,
    -- 'simple' keeps every language searchable; english stemming adds plural/verb forms.
    search_tsv    tsvector GENERATED ALWAYS AS (
                      to_tsvector('simple', content) || to_tsvector('english', content)) STORED,
    embedding     real[],                       -- NULL when no embedding model is configured
    UNIQUE (document_id, chunk_index)
);
CREATE INDEX knowledge_chunks_doctor_idx ON knowledge.chunks (doctor_id);
CREATE INDEX knowledge_chunks_tsv_idx ON knowledge.chunks USING gin (search_tsv);
CREATE INDEX knowledge_chunks_trgm_idx ON knowledge.chunks USING gin (content gin_trgm_ops);

-- migrate:down
DROP TABLE IF EXISTS knowledge.chunks;
DROP TABLE IF EXISTS knowledge.documents;
DROP SCHEMA IF EXISTS knowledge;
