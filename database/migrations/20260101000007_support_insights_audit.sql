CREATE VIEW public.patients_analytics_view AS
SELECT
    p.id AS patient_id,
    coalesce(v.total_visits, 0) AS total_visits,
    v.last_visit_date,
    CASE WHEN v.first_visit IS NULL THEN 0.0
         ELSE round((v.total_visits / greatest(1, extract(epoch FROM now() - v.first_visit) / 2629800.0))::numeric, 2)::float8
    END AS avg_visits_per_month,
    coalesce(vt.vitals_recorded_count, 0) AS vitals_recorded_count,
    vt.last_vital_date,
    CASE WHEN coalesce(vt.vitals_recorded_count, 0) = 0 THEN 0.0
         ELSE least(1.0, vt.active_months / 12.0)::float8 END AS tracking_consistency_score,
    (SELECT count(*) FROM public.medical_conditions mc
      WHERE mc.patient_id = p.id AND mc.is_active AND mc.resolved_date IS NULL)::int AS active_conditions_count,
    (SELECT count(*) FROM public.medications_view m
      WHERE m.patient_id = p.id AND m.status = 'active')::int AS active_medications_count,
    (SELECT count(*) FROM public.medical_exam_orders_view o
      WHERE o.patient_id = p.id AND coalesce(o.scheduled_date, o.ordered_date) >= current_date)::int AS pending_exams_count,
    coalesce(cv.total_conversations, 0) AS total_conversations,
    cv.last_conversation_date
FROM public.patients p
LEFT JOIN LATERAL (
    SELECT count(*)::int AS total_visits, max(start_time) AS last_visit_date, min(start_time) AS first_visit
    FROM public.medical_visits WHERE patient_id = p.id
) v ON true
LEFT JOIN LATERAL (
    SELECT count(*)::int AS vitals_recorded_count, max(recorded_at) AS last_vital_date,
           count(DISTINCT date_trunc('month', recorded_at)) FILTER (WHERE recorded_at > now() - interval '12 months') AS active_months
    FROM public.medical_vitals WHERE patient_id = p.id
) vt ON true
LEFT JOIN LATERAL (
    SELECT count(*)::int AS total_conversations, max(updated_at) AS last_conversation_date
    FROM dialog.conversations WHERE patient_id = p.id AND assistant = 'mediaid'
) cv ON true
WHERE p.deleted_at IS NULL;

CREATE VIEW public.doctors_analytics_view AS
SELECT
    d.id AS doctor_id,
    coalesce(c.total_convos, 0) AS total_convos,
    coalesce(c.avg_hours, 0.0) AS avg_conversation_duration_hours,
    coalesce(c.unique_patients, 0) AS unique_patients_count
FROM public.doctors d
LEFT JOIN LATERAL (
    SELECT count(*)::int AS total_convos,
           count(DISTINCT patient_id)::int AS unique_patients,
           round(avg(extract(epoch FROM updated_at - created_at) / 3600.0)::numeric, 2)::float8 AS avg_hours
    FROM dialog.conversations WHERE doctor_id = d.id AND assistant = 'medidoc'
) c ON true
WHERE d.deleted_at IS NULL;

