CREATE TYPE support.ticket_status AS ENUM ('open', 'resolved', 'closed');
CREATE TYPE support.ticket_priority AS ENUM ('low', 'medium', 'high', 'critical');
CREATE TYPE support.ticket_category AS ENUM ('technical', 'billing', 'feedback', 'account');

CREATE TABLE support.tickets (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject        text NOT NULL,
    body           jsonb NOT NULL DEFAULT '{}',
    category       support.ticket_category NOT NULL DEFAULT 'technical',
    priority       support.ticket_priority NOT NULL DEFAULT 'medium',
    status         support.ticket_status NOT NULL DEFAULT 'open',
    tags           text[] NOT NULL DEFAULT '{}',
    created_by     integer REFERENCES auth.users(id) ON DELETE SET NULL,
    assigned_to    integer REFERENCES hr.staff(id) ON DELETE SET NULL,
    attachments    jsonb NOT NULL DEFAULT '[]',
    user_comments  jsonb NOT NULL DEFAULT '[]',
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    closed_at      timestamptz
);
CREATE INDEX tickets_creator ON support.tickets (created_by, created_at DESC);

CREATE VIEW support.tickets_view AS
SELECT
    t.id, t.id AS ticket_id, t.subject, t.body, t.body->>'description' AS description,
    t.status::text AS status, t.status::text AS ticket_status,
    t.priority::text AS priority, t.category::text AS category, t.tags,
    t.created_by AS creator_user_id,
    coalesce(u.role, 'system') AS creator_role,
    coalesce(
        nullif(trim(coalesce(d.first_name, p.first_name, '') || ' ' || coalesce(d.last_name, p.last_name, '')), ''),
        u.email, 'System') AS creator_name,
    coalesce(d.id, p.id) AS clinical_id,
    s.name AS specialty, c.name AS country,
    st.user_id AS assigned_user_id,
    nullif(trim(coalesce(st.first_name, '') || ' ' || coalesce(st.last_name, '')), '') AS assigned_staff_name,
    st.staff_level,
    t.body->>'domain' AS domain, t.body->>'coverage' AS coverage, t.body->>'lang' AS lang,
    t.created_at, t.updated_at, t.closed_at
FROM support.tickets t
LEFT JOIN auth.users u ON u.id = t.created_by
LEFT JOIN public.doctors d ON d.user_id = t.created_by
LEFT JOIN public.patients p ON p.user_id = t.created_by AND p.relationship = 'main'
LEFT JOIN public.specialties s ON s.id = d.specialty_id
LEFT JOIN public.countries c ON c.id = d.country_id
LEFT JOIN hr.staff st ON st.id = t.assigned_to;

