CREATE TABLE auth.users (
    id                     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                  text,
    phone_number           text,
    password               text NOT NULL,              -- bcrypt hash, never plaintext
    role                   text NOT NULL CHECK (role IN ('patient','doctor','admin')),
    account_status         text NOT NULL DEFAULT 'active'
                           CHECK (account_status IN ('active','inactive','suspended','locked','pending','verified')),
    signup_step            integer NOT NULL DEFAULT 1,
    is_email_verified      boolean,
    is_phone_verified      boolean NOT NULL DEFAULT false,
    failed_login_attempts  integer NOT NULL DEFAULT 0,
    locked_until           timestamptz,
    last_login             timestamptz,
    metadata               jsonb NOT NULL DEFAULT '{}',
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now(),
    deleted_at             timestamptz,
    CONSTRAINT users_has_identifier CHECK (email IS NOT NULL OR phone_number IS NOT NULL)
);
CREATE UNIQUE INDEX users_email_key ON auth.users (lower(email)) WHERE email IS NOT NULL AND deleted_at IS NULL;
CREATE UNIQUE INDEX users_phone_key ON auth.users (phone_number) WHERE phone_number IS NOT NULL AND deleted_at IS NULL;
CREATE TRIGGER users_updated_at BEFORE UPDATE ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE auth.user_profiles (
    id                     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                integer NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
    avatar_url             text,
    timezone               text NOT NULL DEFAULT 'UTC',
    language               text NOT NULL DEFAULT 'en',
    notifications_enabled  boolean NOT NULL DEFAULT true,
    is_active              boolean NOT NULL DEFAULT true,
    metadata               jsonb NOT NULL DEFAULT '{}',
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER user_profiles_updated_at BEFORE UPDATE ON auth.user_profiles
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE auth.user_settings (
    id                         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                    integer NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    context_type               text NOT NULL DEFAULT 'default'
                               CHECK (context_type IN ('default','web','mobile','tablet','clinic_dashboard')),
    context_name               text NOT NULL DEFAULT 'default',
    voice_notifications        boolean NOT NULL DEFAULT true,
    email_notifications        boolean NOT NULL DEFAULT true,
    sms_notifications          boolean NOT NULL DEFAULT false,
    push_notifications         boolean NOT NULL DEFAULT true,
    whatsapp_notifications     boolean NOT NULL DEFAULT true,
    medication_reminders       boolean NOT NULL DEFAULT true,
    health_insights            boolean NOT NULL DEFAULT true,
    marketing_notifications    boolean NOT NULL DEFAULT false,
    emergency_only             boolean NOT NULL DEFAULT false,
    max_daily_notifications    integer NOT NULL DEFAULT 10,
    notification_bundling      boolean NOT NULL DEFAULT true,
    data_retention_days        integer NOT NULL DEFAULT 90 CHECK (data_retention_days BETWEEN 1 AND 365),
    privacy_level              text NOT NULL DEFAULT 'standard' CHECK (privacy_level IN ('standard','high','maximum')),
    share_data_with_providers  boolean NOT NULL DEFAULT true,
    theme                      text NOT NULL DEFAULT 'light' CHECK (theme IN ('light','dark','auto')),
    default_view               text NOT NULL DEFAULT 'dashboard',
    items_per_page             integer NOT NULL DEFAULT 20 CHECK (items_per_page > 0),
    auto_save                  boolean NOT NULL DEFAULT true,
    preferred_contact_method   text NOT NULL DEFAULT 'email'
                               CHECK (preferred_contact_method IN ('email','sms','phone','app','whatsapp')),
    appointment_reminders      boolean NOT NULL DEFAULT true,
    reminder_advance_hours     integer NOT NULL DEFAULT 24 CHECK (reminder_advance_hours >= 0),
    device_token               text,
    fingerprint_enabled        boolean NOT NULL DEFAULT false,
    auto_logout_minutes        integer NOT NULL DEFAULT 60 CHECK (auto_logout_minutes > 0),
    backup_phone               text,
    metadata                   jsonb NOT NULL DEFAULT '{}',
    is_active                  boolean NOT NULL DEFAULT true,
    is_default                 boolean NOT NULL DEFAULT false,
    created_at                 timestamptz NOT NULL DEFAULT now(),
    updated_at                 timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, context_type, context_name)
);
CREATE TRIGGER user_settings_updated_at BEFORE UPDATE ON auth.user_settings
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE auth.refresh_tokens (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     integer NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    token_hash  text NOT NULL UNIQUE,                  -- sha256 of the opaque token
    expires_at  timestamptz NOT NULL,
    revoked     boolean NOT NULL DEFAULT false,
    revoked_at  timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX refresh_tokens_user_active ON auth.refresh_tokens (user_id) WHERE NOT revoked;

CREATE TABLE auth.token_blacklist (
    token_hash  text PRIMARY KEY,
    user_id     integer REFERENCES auth.users(id) ON DELETE CASCADE,
    expires_at  timestamptz NOT NULL,
    revoked_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX token_blacklist_expires ON auth.token_blacklist (expires_at);

CREATE TABLE auth.login_attempts (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           text NOT NULL,
    ip_address      text,
    user_agent      text,
    success         boolean NOT NULL,
    failure_reason  text,
    attempted_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX login_attempts_email_time ON auth.login_attempts (email, attempted_at DESC);

-- One-time codes for email/phone verification and password reset.
-- Only a SHA-256 digest of the code is stored; codes lock after too many attempts.
CREATE TABLE auth.verification_codes (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         text,
    phone_number  text,
    code_hash     text NOT NULL,
    code_type     text NOT NULL CHECK (code_type IN ('email_verification','phone_verification','password_reset')),
    attempts      integer NOT NULL DEFAULT 0,
    expires_at    timestamptz NOT NULL,
    used_at       timestamptz,
    created_at    timestamptz NOT NULL DEFAULT now(),
    CHECK (email IS NOT NULL OR phone_number IS NOT NULL)
);
CREATE INDEX verification_codes_email ON auth.verification_codes (email, code_type, created_at DESC);
CREATE INDEX verification_codes_phone ON auth.verification_codes (phone_number, code_type, created_at DESC);

-- One row per user: account + profile + default settings. Never exposes the password hash.
CREATE VIEW auth.users_view AS
SELECT
    u.id, u.email, u.phone_number, u.role, u.account_status, u.signup_step,
    u.is_email_verified, u.is_phone_verified, u.failed_login_attempts,
    u.locked_until, u.last_login, u.metadata, u.created_at, u.updated_at, u.deleted_at,
    p.avatar_url, p.timezone, p.language AS profile_language, p.notifications_enabled,
    p.is_active AS profile_active, p.metadata AS profile_metadata,
    s.context_type, s.context_name, s.voice_notifications, s.email_notifications,
    s.sms_notifications, s.push_notifications, s.data_retention_days, s.privacy_level,
    s.share_data_with_providers, s.theme, s.default_view, s.items_per_page, s.auto_save,
    s.preferred_contact_method, s.appointment_reminders, s.reminder_advance_hours,
    s.fingerprint_enabled, s.auto_logout_minutes, s.is_active AS settings_active,
    s.is_default AS settings_default, s.whatsapp_notifications, s.medication_reminders,
    s.health_insights, s.marketing_notifications, s.emergency_only, s.max_daily_notifications,
    s.notification_bundling, s.backup_phone, s.metadata AS settings_metadata
FROM auth.users u
LEFT JOIN auth.user_profiles p ON p.user_id = u.id
LEFT JOIN LATERAL (
    SELECT * FROM auth.user_settings us
    WHERE us.user_id = u.id
    ORDER BY us.is_default DESC, us.id
    LIMIT 1
) s ON true;

