-- ---------------------------------------------------------------------------
-- Patients. A user account owns one 'main' patient plus any dependents.
-- ---------------------------------------------------------------------------
CREATE TABLE public.patients (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id         uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    user_id             integer REFERENCES auth.users(id) ON DELETE CASCADE,
    first_name          text,
    last_name           text,
    dob                 date,
    gender              text CHECK (gender IN ('MALE','FEMALE','UNDISCLOSED')),
    relationship        text NOT NULL DEFAULT 'main'
                        CHECK (relationship IN ('main','self','spouse','child','parent','sibling',
                                                'grandparent','grandchild','guardian','other')),
    wa_number           text,
    status              text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE','SUSPENDED')),
    country_id          integer REFERENCES public.countries(id),
    language_id         integer REFERENCES public.languages(id),
    contact             jsonb,
    address             jsonb,
    emergency_contact   jsonb DEFAULT '[]',
    metadata            jsonb DEFAULT '{}',
    medical_data        jsonb,
    insurance_coverage  jsonb,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    deleted_at          timestamptz
);
CREATE UNIQUE INDEX patients_one_main_per_user ON public.patients (user_id)
    WHERE relationship = 'main' AND deleted_at IS NULL;
CREATE INDEX patients_user ON public.patients (user_id);
CREATE INDEX patients_wa_number ON public.patients (wa_number);
CREATE TRIGGER patients_updated_at BEFORE UPDATE ON public.patients
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ---------------------------------------------------------------------------
-- Doctors (in-network, i.e. registered on the platform)
-- ---------------------------------------------------------------------------
CREATE TABLE public.doctors (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id         uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    user_id             integer UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
    prefix              text DEFAULT 'Dr.',
    first_name          text,
    last_name           text,
    gender              text CHECK (gender IN ('MALE','FEMALE','UNDISCLOSED')),
    wa_number           text,
    avatar_url          text,
    medical_licence     text,
    established_since   timestamptz,
    specialty_id        integer REFERENCES public.specialties(id),
    other_specialties   integer[] DEFAULT '{}',
    country_id          integer REFERENCES public.countries(id),
    region_id           integer REFERENCES public.regions(id),
    language_id         integer REFERENCES public.languages(id),
    languages           integer[] DEFAULT '{}',
    status              text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE','SUSPENDED')),
    in_network          boolean NOT NULL DEFAULT true,
    contact             jsonb,
    address             jsonb,
    other_locations     jsonb DEFAULT '[]',
    working_hours       jsonb DEFAULT '[]',
    medical_procedures  jsonb DEFAULT '[]',
    certifications      jsonb DEFAULT '[]',
    metadata            jsonb DEFAULT '{}',
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    deleted_at          timestamptz
);
CREATE INDEX doctors_specialty ON public.doctors (specialty_id);
CREATE INDEX doctors_country ON public.doctors (country_id);
CREATE INDEX doctors_name_trgm ON public.doctors
    USING gin ((coalesce(first_name,'') || ' ' || coalesce(last_name,'')) gin_trgm_ops);
CREATE TRIGGER doctors_updated_at BEFORE UPDATE ON public.doctors
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Out-of-network doctor directory (imported from public sources, no account).
CREATE TABLE public.doctors_oon (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prefix        text DEFAULT 'Dr.',
    first_name    text,
    last_name     text,
    wa_number     text,
    specialty_id  integer REFERENCES public.specialties(id),
    country_id    integer REFERENCES public.countries(id),
    language_id   integer REFERENCES public.languages(id),
    contact       jsonb,
    address       jsonb,
    data_source   text,
    status        text NOT NULL DEFAULT 'ACTIVE',
    created_at    timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Read models
-- ---------------------------------------------------------------------------
CREATE VIEW public.countries_view AS
SELECT id, name, iso_code, phone_code FROM public.countries;

CREATE VIEW public.specialties_view AS
SELECT s.id AS specialty_id, s.name AS specialty_name, s.super_category_id,
       sc.name AS super_category_name
FROM public.specialties s
LEFT JOIN public.specialty_super_categories sc ON sc.id = s.super_category_id;

CREATE VIEW public.patients_view AS
SELECT
    p.id, p.external_id, p.user_id, p.first_name, p.last_name, p.dob, p.gender, p.relationship,
    p.wa_number, p.status, p.country_id, c.name AS country_name, p.language_id, l.name AS language_name,
    CASE WHEN p.dob IS NOT NULL THEN date_part('year', age(p.dob))::int END AS current_age,
    p.contact, p.address, p.emergency_contact, p.metadata, p.medical_data, p.insurance_coverage,
    p.created_at, p.updated_at
FROM public.patients p
LEFT JOIN public.countries c ON c.id = p.country_id
LEFT JOIN public.languages l ON l.id = p.language_id
WHERE p.deleted_at IS NULL;

CREATE VIEW public.doctors_view AS
SELECT
    d.id, d.user_id, d.first_name, d.last_name, d.prefix, d.wa_number, d.avatar_url,
    d.medical_licence, d.gender,
    d.specialty_id, s.name AS specialty_name, s.super_category_id,
    d.country_id, c.name AS country_name, d.region_id, r.name AS region_name,
    d.language_id, l.name AS language_name,
    d.status, CASE WHEN d.in_network THEN 'IN_NETWORK' ELSE 'OUT_OF_NETWORK' END AS network_status,
    d.created_at, d.updated_at, d.established_since,
    trim(coalesce(d.prefix || ' ', '') || coalesce(d.first_name, '') || ' ' || coalesce(d.last_name, '')) AS display_name,
    trim(coalesce(d.first_name, '') || ' ' || coalesce(d.last_name, '')) AS full_name,
    s.name AS specialty, c.name AS country, l.name AS language, d.wa_number AS whatsapp_number
FROM public.doctors d
LEFT JOIN public.specialties s ON s.id = d.specialty_id
LEFT JOIN public.countries c ON c.id = d.country_id
LEFT JOIN public.regions r ON r.id = d.region_id
LEFT JOIN public.languages l ON l.id = d.language_id
WHERE d.deleted_at IS NULL;

CREATE VIEW public.doctors_details_view AS
SELECT
    d.id, d.user_id, d.medical_licence, d.medical_procedures, d.certifications, d.languages,
    d.other_specialties, d.working_hours, d.other_locations, d.contact, d.address,
    d.metadata, d.gender, d.established_since
FROM public.doctors d
WHERE d.deleted_at IS NULL;

CREATE VIEW public.doctors_discovery_view AS
SELECT
    d.id, d.user_id, d.first_name, d.last_name, d.prefix, d.gender,
    d.specialty_id, s.name AS specialty_name, s.super_category_id,
    d.country_id, c.name AS country_name, d.language_id, l.name AS language_name,
    d.contact, d.address, d.avatar_url, d.status, d.in_network
FROM public.doctors d
LEFT JOIN public.specialties s ON s.id = d.specialty_id
LEFT JOIN public.countries c ON c.id = d.country_id
LEFT JOIN public.languages l ON l.id = d.language_id
WHERE d.deleted_at IS NULL;

CREATE VIEW public.doctors_oon_view AS
SELECT
    o.id, o.prefix, o.first_name, o.last_name,
    trim(coalesce(o.first_name, '') || ' ' || coalesce(o.last_name, '')) AS full_name,
    o.wa_number, o.specialty_id, s.name AS specialty_name, s.super_category_id,
    o.country_id, c.name AS country_name, o.language_id, l.name AS language_name,
    o.contact, o.address, o.data_source, o.status
FROM public.doctors_oon o
LEFT JOIN public.specialties s ON s.id = o.specialty_id
LEFT JOIN public.countries c ON c.id = o.country_id
LEFT JOIN public.languages l ON l.id = o.language_id;

