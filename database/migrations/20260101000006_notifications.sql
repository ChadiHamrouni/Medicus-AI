-- Versioned, immutable message templates (Jinja2 bodies).
CREATE TABLE notif.notification_templates (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key         text NOT NULL,
    version     integer NOT NULL DEFAULT 1,
    channel     text NOT NULL CHECK (channel IN ('push','email','sms')),
    language    text NOT NULL DEFAULT 'en',
    title       text,
    body        text NOT NULL,
    is_active   boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (key, version, channel, language)
);
CREATE INDEX notification_templates_lookup ON notif.notification_templates (key, channel, language) WHERE is_active;

-- Notifications are stored per recipient role so preferences/FKs stay strict.
CREATE TABLE notif.patient_notifications (
    id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              integer NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    patient_id           integer REFERENCES public.patients(id) ON DELETE CASCADE,
    template_key         text NOT NULL,
    template_version     integer NOT NULL,
    category             text NOT NULL
                         CHECK (category IN ('rx','appointment','care_plan','messages','lab_results','billing','security')),
    priority             text NOT NULL DEFAULT 'normal' CHECK (priority IN ('low','normal','high','critical')),
    channels             text[] NOT NULL,
    send_after           timestamptz,
    payload              jsonb NOT NULL DEFAULT '{}',
    status               text NOT NULL DEFAULT 'queued'
                         CHECK (status IN ('queued','processing','sent','failed','cancelled')),
    idempotency_key      text NOT NULL UNIQUE,
    attempts             integer NOT NULL DEFAULT 0,
    error_message        text,
    cancellation_reason  text,
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX patient_notifications_due ON notif.patient_notifications (send_after) WHERE status = 'queued';
CREATE INDEX patient_notifications_user ON notif.patient_notifications (user_id, created_at DESC);
CREATE INDEX patient_notifications_appointment ON notif.patient_notifications ((payload->>'appointment_id'))
    WHERE status = 'queued';
CREATE TRIGGER patient_notifications_updated_at BEFORE UPDATE ON notif.patient_notifications
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

