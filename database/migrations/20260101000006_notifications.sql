CREATE VIEW notif.patient_channel_settings_view AS
SELECT p.id AS patient_id,
       coalesce(s.push_enabled, true) AS push_enabled,
       coalesce(s.email_enabled, true) AS email_enabled,
       coalesce(s.sms_enabled, false) AS sms_enabled,
       coalesce(s.quiet_hours_enabled, false) AS quiet_hours_enabled,
       s.quiet_hours_start, s.quiet_hours_end,
       coalesce(s.timezone, 'UTC') AS timezone
FROM public.patients p
LEFT JOIN notif.patient_channel_settings s ON s.patient_id = p.id;

CREATE VIEW notif.doctor_channel_settings_view AS
SELECT d.id AS doctor_id,
       coalesce(s.push_enabled, true) AS push_enabled,
       coalesce(s.email_enabled, true) AS email_enabled,
       coalesce(s.sms_enabled, false) AS sms_enabled,
       coalesce(s.quiet_hours_enabled, false) AS quiet_hours_enabled,
       s.quiet_hours_start, s.quiet_hours_end,
       coalesce(s.timezone, 'UTC') AS timezone
FROM public.doctors d
LEFT JOIN notif.doctor_channel_settings s ON s.doctor_id = d.id;

CREATE VIEW notif.patient_category_settings_view AS
SELECT p.id AS patient_id, c.category, coalesce(s.enabled, true) AS enabled
FROM public.patients p
CROSS JOIN unnest(ARRAY['rx','appointment','care_plan','messages','lab_results','billing','security']) AS c(category)
LEFT JOIN notif.patient_category_settings s ON s.patient_id = p.id AND s.category = c.category;

CREATE VIEW notif.doctor_category_settings_view AS
SELECT d.id AS doctor_id, c.category, coalesce(s.enabled, true) AS enabled
FROM public.doctors d
CROSS JOIN unnest(ARRAY['appointment','messages','schedule_change','security']) AS c(category)
LEFT JOIN notif.doctor_category_settings s ON s.doctor_id = d.id AND s.category = c.category;

